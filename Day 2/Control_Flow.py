# Boolean Condition

age = 25
print(age >= 18)  # Result will be True


# if condition

score = 35

if score >= 35:
    print("You are eligible & Pass!!!")


# if-else condition

if score >= 35:
    print("You are eligible & Pass!!!")
else:
    print("You are not eligible & Fail!!!")


# if-elif-else condition

marks = 70

if marks >= 80:
    print("You are excellent")
elif marks >= 60 and marks <= 80:
    print("You are good")
else:
    print("You are bad")

